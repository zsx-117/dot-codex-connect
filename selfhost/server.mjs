import './build.mjs';
import {createHttpServer} from './http.mjs';
import {mkdirSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {database,checkConfig,createApp} from './core.mjs';
process.umask(0o077);
const config={mcpToken:process.env.DOT_MCP_TOKEN,deviceToken:process.env.DOT_DEVICE_TOKEN};
if(process.env.DOT_AUTH_MODE==='oauth')config.oauth={resource:process.env.DOT_OAUTH_RESOURCE,issuer:process.env.DOT_OAUTH_ISSUER,jwksUri:process.env.DOT_OAUTH_JWKS_URI,subject:process.env.DOT_OAUTH_SUBJECT,clientId:process.env.DOT_OAUTH_CLIENT_ID,scope:process.env.DOT_OAUTH_SCOPE??'codex:bridge'};
else if(process.env.DOT_AUTH_MODE&&process.env.DOT_AUTH_MODE!=='static')throw new Error('Invalid DOT_AUTH_MODE');
checkConfig(config);
const filename=resolve(process.env.DOT_DATABASE??'./state/bridge.sqlite');
mkdirSync(dirname(filename),{recursive:true,mode:0o700});
const store=database(filename);
const app=await createApp(store,config);
const port=Number(process.env.DOT_PORT??8787);
if(!Number.isInteger(port)||port<1||port>65535)throw new Error('Invalid DOT_PORT');
const server=createHttpServer(app);
server.listen(port,'127.0.0.1',()=>console.log('Self-host service listening on loopback. Request bodies are not logged.'));
for(const signal of ['SIGINT','SIGTERM'])process.on(signal,()=>server.close(()=>{store.sql.close();process.exit(0);}));
